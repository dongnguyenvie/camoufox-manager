//! Camoufox Manager — domain types and the traits every other crate talks through.
//!
//! No I/O here: storage (`cm-store`), the browser engine (`cm-engine-camoufox`), the proxy relay
//! (`cm-relay`) and HTTP (`cm-api`) implement or consume these traits; `cm-service` holds the
//! use-cases and only sees `Arc<dyn Trait>`.
//!
//! One module per area. Later phases may add methods to the traits **additively** (prefer a default
//! body returning [`not_implemented`] so other implementations keep compiling).
//!
//! | area | module | traits |
//! |---|---|---|
//! | engine / lifecycle | [`engine`] | [`Engine`] |
//! | profiles | [`profile`] | [`ProfileRepo`] |
//! | proxies | [`proxy`] | [`ProxyRepo`], [`ProxyChecker`] |
//! | organization | [`org`] | [`TagRepo`], [`GroupRepo`], [`SavedViewRepo`] |
//! | templates + extensions | [`template`] | [`TemplateRepo`], [`ExtensionRepo`] |
//! | scheduling | [`schedule`] | [`ScheduleRepo`] |
//! | settings | [`settings`] | [`SettingsRepo`] |
//! | cookies | [`cookies`] | (via [`Engine`]) |
//! | transfer | [`transfer`] | — (types only) |
//! | sheets | [`sheets`] | — (types only) |
//! | time | [`clock`] | [`Clock`] |

pub mod clock;
pub mod cookies;
pub mod engine;
pub mod error;
pub mod org;
pub mod profile;
pub mod proxy;
pub mod schedule;
pub mod settings;
pub mod sheets;
pub mod template;
pub mod transfer;

pub use clock::{Clock, SystemClock};
pub use engine::{Engine, EngineHint, EngineStatus, LaunchOptions, MachineSummary, Session};
pub use error::{CmError, not_implemented};
pub use org::{Group, GroupRepo, SavedView, SavedViewRepo, Tag, TagRepo};
pub use profile::{CanvasMode, NewProfile, Os, Profile, ProfileRepo, ProfileSettings, WebRtcMode};
pub use proxy::{NewProxy, Proxy, ProxyCheck, ProxyChecker, ProxyId, ProxyRepo, ProxyScheme};
pub use schedule::{Schedule, ScheduleAction, ScheduleKind, ScheduleRepo, ScheduleRun, ScheduleRunOutcome};
pub use settings::SettingsRepo;
pub use template::{Extension, ExtensionRepo, Template, TemplateRepo};

/// Profile ids are generated by the app: 24 lowercase hex chars.
pub type ProfileId = String;

/// Result type used across the workspace. Typed failures travel as [`CmError`] inside it.
pub type Result<T> = anyhow::Result<T>;
